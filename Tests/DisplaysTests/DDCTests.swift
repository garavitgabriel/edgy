import Testing

@testable import Displays

// Fixtures are computed by hand from the DDC/CI rules, not by the builder under test:
// host → monitor checksum = 0x6E ^ every byte; monitor → host checksum = 0x50 ^ every byte.

@Test func setVCPPacketMatchesHandComputedBytes() {
  // 0x6E^0x51=0x3F, ^0x84=0xBB, ^0x03=0xB8, ^0x10=0xA8, ^0x00=0xA8, ^0x32=0x9A
  #expect(DDC.setVCP(0x10, value: 50) == [0x51, 0x84, 0x03, 0x10, 0x00, 0x32, 0x9A])
}

@Test func setVCPPacketSplitsSixteenBitValues() {
  // 0x3F^0x84^0x03^0x10 = 0xA8, ^0x01=0xA9, ^0x2C=0x85
  #expect(DDC.setVCP(0x10, value: 300) == [0x51, 0x84, 0x03, 0x10, 0x01, 0x2C, 0x85])
}

@Test func getVCPRequestMatchesHandComputedBytes() {
  // 0x3F^0x82=0xBD, ^0x01=0xBC, ^0x10=0xAC
  #expect(DDC.getVCPRequest(0x10) == [0x51, 0x82, 0x01, 0x10, 0xAC])
}

/// Reply: current 50, max 100. 0x50^0x6E=0x3E, ^0x88=0xB6, ^0x02=0xB4, ^0x10=0xA4, ^0x64=0xC0, ^0x32=0xF2
private let validReply: [UInt8] = [0x6E, 0x88, 0x02, 0x00, 0x10, 0x00, 0x00, 0x64, 0x00, 0x32, 0xF2]

@Test func parsesValidGetVCPReply() throws {
  #expect(try DDC.parseGetVCPReply(validReply, code: 0x10) == DDC.VCPValue(current: 50, maximum: 100))
}

@Test func parseIgnoresTrailingPadding() throws {
  #expect(try DDC.parseGetVCPReply(validReply + [0x00], code: 0x10) == DDC.VCPValue(current: 50, maximum: 100))
}

@Test func parseRejectsBadChecksum() {
  var reply = validReply
  reply[10] ^= 0x01
  #expect(throws: DDC.ReplyError.badChecksum) { try DDC.parseGetVCPReply(reply, code: 0x10) }
}

@Test func parseRejectsCorruptedPayloadThroughChecksum() {
  var reply = validReply
  reply[9] = 0x33
  #expect(throws: DDC.ReplyError.badChecksum) { try DDC.parseGetVCPReply(reply, code: 0x10) }
}

@Test func parseRejectsWrongVCPCode() {
  // Same reply for code 0x12 (contrast): 0xB4^0x12=0xA6, ^0x64=0xC2, ^0x32=0xF0
  let reply: [UInt8] = [0x6E, 0x88, 0x02, 0x00, 0x12, 0x00, 0x00, 0x64, 0x00, 0x32, 0xF0]
  #expect(throws: DDC.ReplyError.wrongCode(expected: 0x10, got: 0x12)) {
    try DDC.parseGetVCPReply(reply, code: 0x10)
  }
}

@Test func parseRejectsWrongOpcode() {
  // Opcode 0x03 instead of 0x02: 0xB6^0x03=0xB5, ^0x10=0xA5, ^0x64=0xC1, ^0x32=0xF3
  let reply: [UInt8] = [0x6E, 0x88, 0x03, 0x00, 0x10, 0x00, 0x00, 0x64, 0x00, 0x32, 0xF3]
  #expect(throws: DDC.ReplyError.unexpectedOpcode(0x03)) { try DDC.parseGetVCPReply(reply, code: 0x10) }
}

@Test func parseRejectsShortReply() {
  #expect(throws: DDC.ReplyError.tooShort(4)) { try DDC.parseGetVCPReply([0x6E, 0x80, 0xBE, 0x00], code: 0x10) }
  #expect(throws: DDC.ReplyError.tooShort(0)) { try DDC.parseGetVCPReply([], code: 0x10) }
}

@Test func parseReportsUnsupportedFeature() {
  // Result code 0x01: 0xB4^0x01=0xB5, ^0x10=0xA5 (all value bytes zero)
  let reply: [UInt8] = [0x6E, 0x88, 0x02, 0x01, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0xA5]
  #expect(throws: DDC.ReplyError.unsupported(0x10)) { try DDC.parseGetVCPReply(reply, code: 0x10) }
}

@Test func parseAcceptsMaximumZeroForTheCallerToReject() throws {
  // Max 0, current 0: 0xA4 ^ 0 = 0xA4. Framing is valid; the probe decides it is unusable.
  let reply: [UInt8] = [0x6E, 0x88, 0x02, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0xA4]
  #expect(try DDC.parseGetVCPReply(reply, code: 0x10) == DDC.VCPValue(current: 0, maximum: 0))
}
