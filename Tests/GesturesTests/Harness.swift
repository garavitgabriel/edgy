import EdgyCore
import Foundation
import Testing

@testable import Gestures

struct Rejection: Equatable, CustomStringConvertible {
  let id: Int32
  let reason: RejectionReason
  var description: String { "\(id):\(reason.rawValue)" }
}

/// Every output of one replay, frame by frame.
struct Replay {
  let frames: [TouchFrame]
  let outputs: [GestureOutput]

  var events: [GestureEvent] { outputs.flatMap(\.events) }
  var rejections: [Rejection] {
    outputs.flatMap { $0.rejections.map { Rejection(id: $0.contactID, reason: $0.reason) } }
  }
  var slideEvents: [GestureEvent] { events.filter { $0.kind == .slide } }
  var changed: [GestureEvent] { slideEvents.filter { $0.phase == .changed } }
  var neverClaimed: Bool { outputs.allSatisfy(\.claimedContactIDs.isEmpty) }
  /// Seconds since the first frame.
  func relative(_ event: GestureEvent) -> Double { event.timestamp - (frames.first?.timestamp ?? 0) }
}

func replay(
  _ frames: [TouchFrame], device: TouchDeviceInfo = TraceBuilder.defaultDevice, zones: Set<Zone>,
  settings: GestureSettings = .defaults, secondsSinceLastKeyPress: Double? = nil,
  recognizer: GestureRecognizing = makeGestureRecognizer()
) -> Replay {
  let context = GestureContext(
    settings: settings, enabledZones: zones, secondsSinceLastKeyPress: secondsSinceLastKeyPress)
  return Replay(frames: frames, outputs: frames.map { recognizer.process($0, device: device, context: context) })
}

func replay(_ trace: TraceFile, zones: Set<Zone>, settings: GestureSettings = .defaults) -> Replay {
  replay(trace.frames, device: trace.device, zones: zones, settings: settings)
}

/// `claimedContactIDs` must be non-empty exactly from the frame a slide began until the frame it
/// ended or was cancelled — checked on every frame, not just frames with events.
func expectClaimsFollowSlide(_ run: Replay, sourceLocation: SourceLocation = #_sourceLocation) {
  var owning = false
  for (index, output) in run.outputs.enumerated() {
    for event in output.events where event.kind == .slide {
      switch event.phase {
      case .began: owning = true
      case .ended, .cancelled: owning = false
      case .changed: break
      }
    }
    #expect(output.claimedContactIDs.isEmpty == !owning, "frame \(index)", sourceLocation: sourceLocation)
  }
}

